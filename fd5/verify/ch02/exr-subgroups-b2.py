"""exr-subgroups-b2: which subsets of Z/12Z are subgroups; 5.[5] = [25] = [1]; the subgroup
generated by [5] is all of Z/12Z."""
QUOTED = {"sets": {(0, 4, 8): True, (0, 3, 6, 9): True, (0, 5): False, (0, 6): True},
          "neg5": 7, "five5": 1}
for S, ok in QUOTED["sets"].items():
    T = set(S)
    assert all((a - b) % 12 in T for a in T for b in T) == ok
assert (-5) % 12 == QUOTED["neg5"] and (5 + 5) % 12 == 10
assert 25 == 2 * 12 + 1 and (5 * 5) % 12 == QUOTED["five5"]
assert {(k * 5) % 12 for k in range(12)} == set(range(12))
assert (-4) % 12 == 8 and (-8) % 12 == 4 and (-3) % 12 == 9 and (-9) % 12 == 3 and (-6) % 12 == 6
print("exr-subgroups-b2: ok")
