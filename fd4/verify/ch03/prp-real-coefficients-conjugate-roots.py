S3 = Q(0, 0, 1)    # sqrt 3

# --- checks ---
z = C(1, 2)
assert z ** 2 == C(*QUOTED["square"]) and 2 * z == C(2, 4)
assert z ** 2 - 2 * z + 5 == 0 and z.conj() ** 2 - 2 * z.conj() + 5 == 0
random.seed(3)
for _ in range(200):
    coeffs = [Fr(random.randint(-9, 9), random.randint(1, 5)) for _ in range(random.randint(1, 6))]
    w = C(Fr(random.randint(-9, 9), 7), Fr(random.randint(-9, 9), 5))
    val = C(0); valc = C(0)
    for k, a in enumerate(coeffs):
        val = val + C(a) * w ** k; valc = valc + C(a) * w.conj() ** k
    assert val.conj() == valc
